// Copies the open-licence font files we use from node_modules/@fontsource* to
// public/fonts (stable URLs, so pages can <link rel=preload> them) and writes
// src/styles/fonts.css. Only woff2 is shipped (Baseline-wide support).
//   node tools/build/fonts.mjs
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..', '..');
const OUT = join(ROOT, 'public', 'fonts');
mkdirSync(OUT, { recursive: true });

const sources = [
  ...['300', '400', '500', '600'].flatMap((w) => ['thai', 'latin'].map((s) => ({
    pkg: '@fontsource/ibm-plex-sans-thai', css: `${w}.css`, file: `ibm-plex-sans-thai-${s}-${w}-normal.woff2`,
  }))),
  ...['latin', 'latin-ext'].map((s) => ({ pkg: '@fontsource-variable/manrope', css: 'wght.css', subset: s, file: `manrope-${s}-wght-normal.woff2` })),
];

let css = '/* Generated by tools/build/fonts.mjs — do not edit. Fonts: OFL-1.1 (IBM Plex Sans Thai, Manrope). */\n';
for (const s of sources) {
  const dir = join(ROOT, 'node_modules', s.pkg);
  copyFileSync(join(dir, 'files', s.file), join(OUT, s.file));
  const src = readFileSync(join(dir, s.css), 'utf8');
  // Pick the @font-face block that references this file (wght.css holds several subsets).
  const block = src.split('@font-face').find((b) => b.includes(s.file));
  if (!block) throw new Error(`No @font-face for ${s.file}`);
  const get = (prop) => block.match(new RegExp(`${prop}:\\s*([^;]+);`))?.[1].trim();
  css += `@font-face {
  font-family: ${get('font-family')};
  font-style: normal;
  font-display: swap;
  font-weight: ${get('font-weight')};
  src: url(/fonts/${s.file}) format('woff2');
  unicode-range: ${get('unicode-range')};
}\n`;
}
writeFileSync(join(ROOT, 'src', 'styles', 'fonts.css'), css);
console.log(`fonts: ${sources.length} files → public/fonts, src/styles/fonts.css`);
